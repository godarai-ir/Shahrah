"use client";

import dynamic from "next/dynamic";
import { type ComponentProps, type Dispatch, type SetStateAction } from "react";
import { useTranslations } from "next-intl";
import { ChevronRight } from "lucide-react";

import { AppSelectField } from "@/components/app-ui/AppSelectField";
import { EntityIdentityHeader } from "@/components/app-ui/EntityIdentityHeader";
import { IdentifierField } from "@/components/app-ui/IdentifierField";
import { PageContainer } from "@/components/app-ui/PageContainer";
import { Alert, AlertDescription, AlertTitle } from "@/components/ui/alert";
import { Button } from "@/components/ui/button";
import {
  Field,
  FieldContent,
  FieldDescription,
  FieldGroup,
  FieldLabel,
  FieldLegend,
  FieldSet,
  FieldTitle,
} from "@/components/ui/field";
import { Progress } from "@/components/ui/progress";
import { RadioGroup, RadioGroupItem } from "@/components/ui/radio-group";
import { Skeleton } from "@/components/ui/skeleton";
import { type PrincipalSearchKind } from "@/components/app-ui/PrincipalEntitySelect";
import { AccessEditor } from "@/features/provider-accounts/access-editor";
import { defaultProviderCredentialValues, type ProviderCredentialValues } from "@/features/provider-accounts/credential-schema";
import { CreateReviewPanel } from "@/features/provider-accounts/create-review-panel";
import { ProviderCredentialSchemaFields } from "@/features/provider-accounts/provider-credential-schema-fields";
import { ProviderPicker } from "@/features/provider-accounts/provider-picker";
import { ProviderLogo } from "@/components/app-ui/ProviderLogo";
import type {
  AccessPrincipal,
  AccessPrincipalCandidate,
  Banner,
  CredentialTestResult,
  ModelDraft,
  ProviderAuthMode,
  ProviderCatalogModel,
  ProviderCatalogProvider,
  ProviderConnectionSchema,
  TenantProviderAccount,
} from "@/features/provider-accounts/types";
import { WIFCredentialStatus } from "@/features/provider-accounts/wif-credential-status";
import { CatalogCreateSection } from "@/features/provider-accounts/wizard-shell";
import { CreateFlowStepIndicator, type CreateWizardSectionID } from "@/features/provider-accounts/wizard-layout";

const ModelsEditor = dynamic(
  () => import("@/features/provider-accounts/models-editor").then((module) => module.ModelsEditor),
  {
    ssr: false,
    loading: () => (
      <div className="flex flex-col gap-3" aria-hidden="true">
        <Skeleton className="h-10 w-full" />
        <Skeleton className="h-40 w-full" />
        <Skeleton className="h-40 w-full" />
      </div>
    ),
  },
);

type Translator = ReturnType<typeof useTranslations>;
type CreateStep = { id: CreateWizardSectionID; number: number; title: string };
type CreateStepState = ComponentProps<typeof CreateFlowStepIndicator>["state"];
type CredentialNotice = (Banner & Partial<CredentialTestResult>) | null;

export type ProviderAccountCreateViewProps = {
  t: Translator;
  ux: Translator;
  catalogT: Translator;
  provider: string;
  name: string;
  activeProvider: ProviderCatalogProvider | null;
  createHeaderProviderName: string;
  banner: Banner | null;
  selectedAccountID: string;
  catalogStepProgressLabel: string;
  catalogActiveStepTitle: string;
  catalogActiveStepNumber: number;
  catalogStepCount: number;
  createWizardSteps: CreateStep[];
  createStepState: (step: CreateWizardSectionID) => CreateStepState;
  canOpenCreateStep: (step: CreateWizardSectionID) => boolean;
  resetCreateProviderSelection: () => void;
  activeCreateSection: CreateWizardSectionID;
  setActiveCreateSection: Dispatch<SetStateAction<CreateWizardSectionID>>;
  visibleProviders: ProviderCatalogProvider[];
  isLoading: boolean;
  providerSearch: string;
  setProviderSearch: Dispatch<SetStateAction<string>>;
  selectCreateProvider: (provider: ProviderCatalogProvider) => void;
  handleContinueFromCreateDetails: () => Promise<void>;
  canCreateProviderAccount: boolean;
  canContinueCreateDetails: boolean;
  requiresSuccessfulCreatePreflight: boolean;
  apiKeyTestSucceeded: boolean;
  isSavingCredentials: boolean;
  setName: Dispatch<SetStateAction<string>>;
  setIsNameAutoGenerated: Dispatch<SetStateAction<boolean>>;
  accountNameConflict: boolean;
  docsBaseHref: string;
  usePlatformManagedCredentials: boolean;
  account: TenantProviderAccount | null;
  setUsePlatformManagedCredentials: Dispatch<SetStateAction<boolean>>;
  setAPIKeyTestSucceeded: Dispatch<SetStateAction<boolean>>;
  setCreateCredentialTestResult: Dispatch<SetStateAction<CredentialNotice>>;
  isLoadingConnectionSchemas: boolean;
  connectionSchemaError: string;
  connectionSchemas: ProviderConnectionSchema[];
  authMode: ProviderAuthMode;
  setAuthMode: Dispatch<SetStateAction<ProviderAuthMode>>;
  setProviderCredentialValues: Dispatch<SetStateAction<ProviderCredentialValues>>;
  selectedConnectionSchema: ProviderConnectionSchema | null;
  providerCredentialValues: ProviderCredentialValues;
  isTesting: boolean;
  handleCreateCredentialTest: () => Promise<void>;
  createCredentialTestResult: CredentialNotice;
  selectedModelCount: number;
  handleContinueFromCreateModels: () => Promise<void>;
  canManageProviderAccount: boolean;
  isSavingModels: boolean;
  setBanner: Dispatch<SetStateAction<Banner | null>>;
  providerModels: ProviderCatalogModel[];
  modelDrafts: Record<string, ModelDraft>;
  setModelDrafts: Dispatch<SetStateAction<Record<string, ModelDraft>>>;
  isLoadingProviderModels: boolean;
  handleSaveModelsAction: (draftOverride?: Record<string, ModelDraft>) => void;
  managers: AccessPrincipal[];
  users: AccessPrincipal[];
  handleContinueFromCreateAccess: () => Promise<void>;
  isSavingAccess: boolean;
  handleManagersChange: (managers: AccessPrincipal[]) => void;
  handleUsersChange: (users: AccessPrincipal[]) => void;
  searchPrincipalCandidates: (kind: PrincipalSearchKind, query: string) => Promise<AccessPrincipalCandidate[]>;
  principalSelectorLabels: ComponentProps<typeof AccessEditor>["principalSelectorLabels"];
  handleSaveAccessAction: () => void;
  currentUserManager: AccessPrincipal | null;
  handleFinishCreateFlow: () => Promise<void>;
  createReady: boolean;
  isActivating: boolean;
  apiKey: string;
  selectedModels: ProviderCatalogModel[];
  unresolvedPricingCount: number;
};

export function ProviderAccountCreateView(props: ProviderAccountCreateViewProps) {
  const {
    t, ux, catalogT, provider, name, activeProvider, createHeaderProviderName, banner, selectedAccountID,
    catalogStepProgressLabel, catalogActiveStepTitle, catalogActiveStepNumber, catalogStepCount,
    createWizardSteps, createStepState, canOpenCreateStep, resetCreateProviderSelection, activeCreateSection,
    setActiveCreateSection, visibleProviders, isLoading, providerSearch, setProviderSearch, selectCreateProvider,
    handleContinueFromCreateDetails, canCreateProviderAccount, canContinueCreateDetails,
    requiresSuccessfulCreatePreflight, apiKeyTestSucceeded, isSavingCredentials, setName,
    setIsNameAutoGenerated, accountNameConflict, docsBaseHref, usePlatformManagedCredentials, account,
    setUsePlatformManagedCredentials, setAPIKeyTestSucceeded, setCreateCredentialTestResult,
    isLoadingConnectionSchemas, connectionSchemaError, connectionSchemas, authMode, setAuthMode,
    setProviderCredentialValues, selectedConnectionSchema, providerCredentialValues, isTesting,
    handleCreateCredentialTest, createCredentialTestResult, selectedModelCount, handleContinueFromCreateModels,
    canManageProviderAccount, isSavingModels, setBanner, providerModels, modelDrafts, setModelDrafts,
    isLoadingProviderModels, handleSaveModelsAction, managers, users, handleContinueFromCreateAccess,
    isSavingAccess, handleManagersChange, handleUsersChange, searchPrincipalCandidates, principalSelectorLabels,
    handleSaveAccessAction, currentUserManager, handleFinishCreateFlow, createReady, isActivating, apiKey,
    selectedModels, unresolvedPricingCount,
  } = props;

    return (
      <PageContainer size="full" spacing="compact" padding="none">
        <header className="flex min-h-14 items-center rounded-xl border border-card-border bg-card px-4 py-3 shadow-xs sm:px-6">
          <div className="flex min-w-0 items-center gap-2 text-base sm:text-lg">
            <span className="shrink-0 text-muted-foreground">{ux("integrations.pageTitle")}</span>
            <ChevronRight className="size-4 shrink-0 text-muted-foreground rtl:rotate-180" />
            {provider ? (
              <span className="flex min-w-0 items-center gap-2 font-semibold">
                <ProviderLogo
                  provider={activeProvider?.provider ?? provider}
                  displayName={createHeaderProviderName}
                  logoURL={activeProvider?.logo_url}
                  size={20}
                  decorative
                />
                <span className="truncate" dir="ltr">{createHeaderProviderName}</span>
              </span>
            ) : (
              <span className="truncate font-semibold">{catalogT("create.providerPlaceholder")}</span>
            )}
          </div>
        </header>

        {banner && banner.kind !== "success" ? (
          <Alert variant={banner.kind === "error" ? "destructive" : "default"}>
            <AlertTitle>{banner.kind === "error" ? t("errorTitle") : t("successTitle")}</AlertTitle>
            <AlertDescription>{banner.message}</AlertDescription>
          </Alert>
        ) : null}

        {selectedAccountID ? (
          <Alert variant="info">
            <AlertTitle>{ux("integrations.wizard.draftSavedTitle")}</AlertTitle>
            <AlertDescription>{ux("integrations.wizard.draftSavedDescription")}</AlertDescription>
          </Alert>
        ) : null}

        <div className="flex min-w-0 flex-1 flex-col gap-4">
          <nav
            aria-label={ux("integrations.pageTitle")}
            className="min-w-0"
          >
            <div className="rounded-xl border border-card-border bg-card p-4 shadow-xs xl:hidden">
              <div className="flex items-center justify-between gap-3">
                <span className="text-xs font-medium text-muted-foreground">
                  {catalogStepProgressLabel}
                </span>
                <span className="text-sm font-semibold">{catalogActiveStepTitle}</span>
              </div>
              <Progress
                value={(catalogActiveStepNumber / catalogStepCount) * 100}
                className="mt-3 h-1.5"
                aria-label={catalogStepProgressLabel}
              />
            </div>
            <div className="hidden grid-cols-5 gap-2 xl:grid">
              <CreateFlowStepIndicator
                number={1}
                title={catalogT("create.chooseProvider")}
                state={provider ? "complete" : "active"}
                variant="compact"
                onClick={resetCreateProviderSelection}
              />
              {createWizardSteps.map((step) => {
                const stepState = createStepState(step.id);
                const isStepOpenable = Boolean(provider) && canOpenCreateStep(step.id);
                return (
                  <CreateFlowStepIndicator
                    key={step.id}
                    number={step.number + 1}
                    title={step.title}
                    state={provider ? stepState : "idle"}
                    variant="compact"
                    disabled={!isStepOpenable}
                    onClick={() => {
                      if (isStepOpenable) setActiveCreateSection(step.id);
                    }}
                  />
                );
              })}
            </div>
          </nav>

          <div className="min-w-0">
            <div className="flex w-full min-w-0 flex-col gap-6 pb-2">
                {!provider ? (
                  <ProviderPicker
                    providers={visibleProviders}
                    isLoading={isLoading}
                    search={providerSearch}
                    onSearchChange={setProviderSearch}
                    onSelect={selectCreateProvider}
                    labels={{
                      cancel: ux("actions.cancelDelete"),
                      search: catalogT("filters.search"),
                      searchPlaceholder: catalogT("filters.searchProviderPicker"),
                      emptyTitle: catalogT("empty.noResultsTitle"),
                      emptyDescription: catalogT("empty.noResultsDescription"),
                    }}
                  />
                ) : (
                  <>
                    {activeCreateSection === "details" ? (
                      <CatalogCreateSection
                        id="connection-details"
                        title=""
                        fillHeight={false}
                        footer={(
                          <div className="flex w-full flex-wrap items-center justify-between gap-2">
                            <Button type="button" variant="outline" onClick={resetCreateProviderSelection}>
                              {ux("actions.back")}
                            </Button>
                            <Button
                              type="button"
                              onClick={() => void handleContinueFromCreateDetails()}
                              disabled={!canCreateProviderAccount || !canContinueCreateDetails || (requiresSuccessfulCreatePreflight && !apiKeyTestSucceeded) || isLoading || isSavingCredentials || !provider || !name.trim()}
                            >
                              {isLoading || isSavingCredentials ? t("saving") : ux("integrations.wizard.nextStep")}
                            </Button>
                          </div>
                        )}
                      >
                        <div className="flex flex-col gap-6">
                          <EntityIdentityHeader
                            title={<span dir="ltr">{createHeaderProviderName}</span>}
                            leading={(
                              <div className="flex size-12 items-center justify-center rounded-lg border border-border bg-muted/30">
                                <ProviderLogo
                                  provider={activeProvider?.provider ?? provider}
                                  displayName={createHeaderProviderName}
                                  logoURL={activeProvider?.logo_url}
                                  size={28}
                                  decorative
                                />
                              </div>
                            )}
                            className="border-b border-border pb-5"
                            titleClassName="flex h-12 items-center"
                          />

                          <IdentifierField
                            id="accountName"
                            label={t("fields.accountName")}
                            value={name}
                            onChange={(event) => {
                              setName(event.target.value);
                              setIsNameAutoGenerated(false);
                            }}
                            placeholder={ux("placeholders.accountName")}
                            disabled={Boolean(selectedAccountID)}
                            error={accountNameConflict ? t("messages.accountNameExists") : undefined}
                            containerClassName="max-w-2xl"
                          />

                      <div className="text-start">
                        <FieldSet className="gap-0">
                          <FieldLegend className="mb-0">
                            {ux("integrations.wizard.useOwnApiKeyQuestion", { providerName: createHeaderProviderName })}
                          </FieldLegend>
                          <FieldDescription className="mt-1 text-sm leading-6">
                            {ux.rich("integrations.wizard.useOwnApiKeyDescription", {
                              guideLink: (chunks) => (
                                <a
                                  href={`${docsBaseHref}/quick-start`}
                                  target="_blank"
                                  rel="noreferrer"
                                  className="font-medium text-primary underline-offset-4 hover:underline"
                                >
                                  {chunks}
                                </a>
                              ),
                            })}
                          </FieldDescription>

                          <RadioGroup
                            name="create-own-api-key"
                            value={usePlatformManagedCredentials ? "platform-managed" : "byok"}
                            onValueChange={(nextValue) => {
                               if (account) return;
                               setUsePlatformManagedCredentials(nextValue === "platform-managed");
                               setAPIKeyTestSucceeded(false);
                               setCreateCredentialTestResult(null);
                            }}
                            disabled={!!account}
                            className="mt-4 grid gap-3 md:grid-cols-2"
                          >
                            <Field
                              orientation="horizontal"
                              className="relative order-1 cursor-pointer items-start rounded-md border border-border p-4 transition-colors hover:bg-muted/30 focus-within:ring-2 focus-within:ring-ring/50 has-[[data-state=checked]]:border-primary has-[[data-state=checked]]:bg-primary/5"
                            >
                              <FieldLabel
                                htmlFor="create-own-api-key-byok"
                                className="absolute inset-0 size-full cursor-pointer rounded-md"
                              >
                                <span className="sr-only">{ux("integrations.wizard.useOwnApiKeyYes")}</span>
                              </FieldLabel>
                              <RadioGroupItem id="create-own-api-key-byok" value="byok" className="pointer-events-none relative z-10 mt-1" />
                              <FieldContent className="pointer-events-none relative z-10 min-w-0">
                                <FieldTitle>
                                  {ux("integrations.wizard.useOwnApiKeyYes")}
                                </FieldTitle>
                                <FieldDescription className="text-sm leading-6">
                                  {ux.rich("integrations.wizard.useOwnApiKeyYesDescription", {
                                    byokLink: (chunks) => (
                                      <a
                                        href={`${docsBaseHref}/guides/byok`}
                                        target="_blank"
                                        rel="noreferrer"
                                        className="pointer-events-auto relative z-20 font-medium text-primary underline-offset-4 hover:underline"
                                      >
                                        {chunks}
                                      </a>
                                    ),
                                  })}
                                </FieldDescription>
                              </FieldContent>
                            </Field>

                            <Field
                              orientation="horizontal"
                              className="relative order-3 cursor-pointer items-start rounded-md border border-border p-4 transition-colors hover:bg-muted/30 focus-within:ring-2 focus-within:ring-ring/50 has-[[data-state=checked]]:border-primary has-[[data-state=checked]]:bg-primary/5 md:order-2"
                            >
                              <FieldLabel
                                htmlFor="create-own-api-key-platform"
                                className="absolute inset-0 size-full cursor-pointer rounded-md"
                              >
                                <span className="sr-only">{ux("integrations.wizard.useOwnApiKeyNo")}</span>
                              </FieldLabel>
                              <RadioGroupItem id="create-own-api-key-platform" value="platform-managed" className="pointer-events-none relative z-10 mt-1" />
                              <FieldContent className="pointer-events-none relative z-10 min-w-0">
                                <FieldTitle>
                                  {ux("integrations.wizard.useOwnApiKeyNo")}
                                </FieldTitle>
                                <FieldDescription className="text-sm leading-6">
                                  {ux("integrations.wizard.useOwnApiKeyNoDescription", { providerName: createHeaderProviderName })}
                                </FieldDescription>
                              </FieldContent>
                            </Field>

                            {!usePlatformManagedCredentials ? (
                              <FieldGroup className="order-2 rounded-e-lg border-s-2 border-primary/40 bg-muted/20 p-4 md:order-3 md:col-span-2 md:rounded-none md:border-s-0 md:bg-transparent md:p-0">
                                {isLoadingConnectionSchemas ? (
                                  <p className="text-sm text-muted-foreground" role="status">
                                    {ux("integrations.wizard.loadingConnectionSchema")}
                                  </p>
                                ) : null}
                                {connectionSchemaError ? (
                                  <Alert variant="destructive">
                                    <AlertTitle>{ux("integrations.wizard.connectionSchemaErrorTitle")}</AlertTitle>
                                    <AlertDescription>{connectionSchemaError}</AlertDescription>
                                  </Alert>
                                ) : null}
                                {connectionSchemas.length > 1 ? (
                                  <AppSelectField
                                    id="createProviderAuthMode"
                                    label={t("fields.authMode")}
                                    value={authMode}
                                    optionTextDir="ltr"
                                    options={connectionSchemas.map((schema) => ({
                                      value: schema.auth_mode,
                                      label: schema.auth_mode,
                                    }))}
                                    onValueChange={(value) => {
                                      const nextSchema = connectionSchemas.find((schema) => schema.auth_mode === value) ?? null;
                                     setAuthMode(value as ProviderAuthMode);
                                     setProviderCredentialValues(defaultProviderCredentialValues(nextSchema));
                                     setAPIKeyTestSucceeded(false);
                                     setCreateCredentialTestResult(null);
                                    }}
                                  />
                                ) : null}
                                {selectedConnectionSchema ? (
                                  <ProviderCredentialSchemaFields
                                    schema={selectedConnectionSchema}
                                    values={providerCredentialValues}
                                    onValueChange={(key, value) => {
                                      setProviderCredentialValues((current) => ({ ...current, [key]: value }));
                                      setAPIKeyTestSucceeded(false);
                                      setCreateCredentialTestResult(null);
                                    }}
                                    disabled={isLoading || isSavingCredentials || isTesting}
                                    connectionFieldsTitle={ux("integrations.wizard.connectionFieldsTitle")}
                                    credentialFieldsTitle={ux("integrations.wizard.credentialFieldsTitle")}
                                    writeOnlyLabel={ux("integrations.wizard.writeOnlyCredential")}
                                    documentationLabel={ux("integrations.wizard.providerDocumentation")}
                                  />
                                ) : null}
                                {provider.trim().toLowerCase() === "zai" ? (
                                  <Alert variant="warning">
                                    <AlertTitle>{ux("connectionTest.warningTitle")}</AlertTitle><AlertDescription>{ux("connectionTest.zaiBillableWarning")}</AlertDescription>
                                  </Alert>
                                ) : null}
                                <div className="flex flex-wrap items-center justify-between gap-3">
                                  <p className="text-sm leading-6 text-muted-foreground">
                                    {ux("integrations.wizard.testConnectionDescription")}
                                  </p>
                                  <Button
                                    type="button"
                                    variant="outline"
                                    onClick={() => void handleCreateCredentialTest()}
                                    disabled={!canCreateProviderAccount || !canContinueCreateDetails || isLoading || isSavingCredentials || isTesting}
                                  >
                                    {isTesting || isSavingCredentials || isLoading
                                      ? ux("integrations.wizard.testingConnection")
                                      : ux("integrations.wizard.testConnection")}
                                  </Button>
                                </div>
                                {createCredentialTestResult ? (
                                  <Alert variant={createCredentialTestResult.kind === "error" ? "destructive" : createCredentialTestResult.kind === "warning" ? "warning" : "default"}>
                                    <AlertTitle>
                                      {createCredentialTestResult.kind === "warning"
                                        ? ux("connectionTest.warningTitle")
                                        : createCredentialTestResult.kind === "error"
                                        ? ux("integrations.wizard.connectionTestFailedTitle")
                                        : ux("integrations.wizard.connectionTestSuccessTitle")}
                                    </AlertTitle>
                                    <AlertDescription>{createCredentialTestResult.message}</AlertDescription>
                                  </Alert>
                                ) : null}
                                <WIFCredentialStatus result={createCredentialTestResult} />
                              </FieldGroup>
                            ) : null}
                          </RadioGroup>
                        </FieldSet>
                      </div>
                    </div>
                      </CatalogCreateSection>
                    ) : null}

                  {activeCreateSection === "models" ? (
                    <CatalogCreateSection
                      id="model-provisioning"
                      title=""
                      fillHeight={false}
                      contentClassName="flex min-h-0 flex-1 flex-col"
                      footer={(
                        <div className="flex w-full flex-wrap items-center justify-between gap-3">
                          <Button type="button" variant="outline" onClick={() => setActiveCreateSection("details")}>
                            {ux("actions.back")}
                          </Button>
                          <div className="flex flex-wrap items-center justify-end gap-3">
                            {selectedModelCount === 0 ? (
                              <span className="text-sm text-destructive">
                                {ux("integrations.wizard.modelSelectionRequired")}
                              </span>
                            ) : null}
                            <Button
                              type="button"
                              onClick={() => void handleContinueFromCreateModels()}
                              disabled={!canManageProviderAccount || selectedModelCount === 0 || isSavingModels}
                            >
                              {isSavingModels ? t("saving") : ux("actions.continue")}
                            </Button>
                          </div>
                        </div>
                      )}
                    >
                    <ModelsEditor
                      t={t}
                      account={account}
                      pendingAccountName={name}
                      pendingProvider={provider}
                      setBanner={setBanner}
                      providerModels={providerModels}
                      modelDrafts={modelDrafts}
                      setModelDrafts={setModelDrafts}
                      isSaving={isSavingModels}
                      isLoadingModels={isLoadingProviderModels}
                      canManage={canManageProviderAccount}
                      onSave={handleSaveModelsAction}
                      variant="compact"
                    />
                  </CatalogCreateSection>
                  ) : null}

                  {activeCreateSection === "access" ? (
                    <CatalogCreateSection
                      id="access-permissions"
                      title={ux("integrations.wizard.accessPermissions")}
                      description={ux("integrations.wizard.accessPermissionsDescription")}
                      fillHeight={false}
                      footer={(
                        <div className="flex w-full flex-wrap items-center justify-between gap-3">
                          <Button type="button" variant="outline" onClick={() => setActiveCreateSection("models")}>
                            {ux("actions.back")}
                          </Button>
                          <div className="flex flex-wrap items-center justify-end gap-3">
                            {managers.length === 0 ? <span className="text-sm text-destructive">{ux("access.managerRequiredHint")}</span> : null}
                            <Button
                              type="button"
                              onClick={() => void handleContinueFromCreateAccess()}
                              disabled={!canManageProviderAccount || managers.length === 0 || isSavingAccess}
                            >
                              {isSavingAccess ? t("saving") : ux("actions.continue")}
                            </Button>
                          </div>
                        </div>
                      )}
                    >
                    <AccessEditor
                      t={t}
                      managers={managers}
                      setManagers={handleManagersChange}
                      users={users}
                      setUsers={handleUsersChange}
                      onSearchPrincipal={searchPrincipalCandidates}
                      principalSelectorLabels={principalSelectorLabels}
                      onSave={handleSaveAccessAction}
                      isSaving={isSavingAccess}
                       canManage={canManageProviderAccount}
                       showSaveAction={false}
                       embedded
                       isManagerRemovable={currentUserManager
                         ? (manager) => !(
                             manager.type === "user"
                             && manager.principal_id === currentUserManager.principal_id
                           )
                         : undefined}
                       getLockedManagerLabel={(manager) => ux("access.currentUserLocked", {
                         identity: manager.display_name || manager.principal_id || manager.type,
                       })}
                     />
                  </CatalogCreateSection>
                  ) : null}

                  {activeCreateSection === "review" ? (
                    <CreateReviewPanel
                      ux={ux}
                      catalogT={catalogT}
                      setActiveCreateSection={setActiveCreateSection}
                      onFinish={handleFinishCreateFlow}
                      createReady={createReady}
                      canCreateProviderAccount={canCreateProviderAccount}
                      isActivating={isActivating}
                      isTesting={isTesting}
                      isLoading={isLoading}
                      hasCredential={Boolean(account?.has_credential)}
                      usePlatformManagedCredentials={usePlatformManagedCredentials}
                      apiKey={apiKey}
                      selectedModels={selectedModels}
                      selectedModelCount={selectedModelCount}
                      unresolvedPricingCount={unresolvedPricingCount}
                      managers={managers}
                      users={users}
                      providerName={createHeaderProviderName}
                      accountName={name}
                      authMode={authMode}
                    />
                  ) : null}
                  </>
                )}
              </div>
            </div>
          </div>
        </PageContainer>
    );
}
