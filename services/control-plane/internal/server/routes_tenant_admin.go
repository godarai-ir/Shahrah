package server

import "github.com/gofiber/fiber/v2"

func registerProtectedRoutes(app *fiber.App, deps Dependencies) {
	registerProxyRoutes(app, deps)
	registerTenantAdminRoutes(app, deps)
	registerTenantAdminAuthRoutes(app, deps)
}

